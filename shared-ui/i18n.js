const pairs = Object.entries(english).sort((a, b) => b[0].length - a[0].length);
const textState = new WeakMap();
const attributeState = new WeakMap();
let language = "en";

function translate(value) {
  if (language === "zh") return value;
  let result = value;
  for (const [source, target] of pairs)
    result = result.replaceAll(source, target);
  return result;
}

export function localize(value) {
  return translate(value);
}

function excluded(element) {
  return element?.closest(
    "script,style,code,pre,[translate='no'],.file-name,.device-name,.transfer-name",
  );
}

function updateText(node) {
  if (excluded(node.parentElement)) return;
  const previous = textState.get(node);
  const source =
    previous && node.nodeValue === previous.rendered
      ? previous.source
      : node.nodeValue;
  const rendered = translate(source);
  textState.set(node, { source, rendered });
  if (node.nodeValue !== rendered) node.nodeValue = rendered;
}

function updateAttributes(element) {
  if (excluded(element)) return;
  const values = attributeState.get(element) || {};
  for (const name of ["placeholder", "title", "aria-label"]) {
    if (!element.hasAttribute(name)) continue;
    const current = element.getAttribute(name);
    const source =
      values[name] && current === values[name].rendered
        ? values[name].source
        : current;
    const rendered = translate(source);
    values[name] = { source, rendered };
    if (current !== rendered) element.setAttribute(name, rendered);
  }
  attributeState.set(element, values);
}

function visit(root) {
  if (root.nodeType === Node.TEXT_NODE) return updateText(root);
  if (root.nodeType !== Node.ELEMENT_NODE || excluded(root)) return;
  updateAttributes(root);
  for (const child of root.childNodes) visit(child);
}

export function installI18n(containers) {
  try {
    language = localStorage.getItem("dukou-language") === "zh" ? "zh" : "en";
  } catch {
    language = "en";
  }
  const buttons = containers
    .map((selector) => {
      const parent = document.querySelector(selector);
      if (!parent) return null;
      const button = document.createElement("button");
      button.type = "button";
      button.className = "language-toggle";
      button.translate = false;
      parent.append(button);
      return button;
    })
    .filter(Boolean);
  function render() {
    document.documentElement.lang = language === "zh" ? "zh-CN" : "en";
    document.title = translate(
      document.title
        .replace("Dukou · Peer transfer", "渡口 · 对等互传")
        .replace("Dukou · Direct transfer", "渡口 · 文件直连"),
    );
    for (const button of buttons) {
      button.textContent = language === "en" ? "中文" : "English";
      button.setAttribute(
        "aria-label",
        language === "en" ? "Switch to Chinese" : "切换到英文",
      );
      button.title = button.getAttribute("aria-label");
    }
    visit(document.body);
    document.documentElement.dataset.i18nReady = "true";
  }
  for (const button of buttons)
    button.onclick = () => {
      language = language === "en" ? "zh" : "en";
      try {
        localStorage.setItem("dukou-language", language);
      } catch {
        /* Storage may be unavailable. */
      }
      render();
    };
  const observer = new MutationObserver((records) => {
    for (const record of records) {
      if (record.type === "characterData") updateText(record.target);
      else if (record.type === "attributes") {
        if (record.attributeName === "translate") visit(record.target);
        else updateAttributes(record.target);
      } else for (const node of record.addedNodes) visit(node);
    }
  });
  observer.observe(document.body, {
    subtree: true,
    childList: true,
    characterData: true,
    attributes: true,
    attributeFilter: ["placeholder", "title", "aria-label", "translate"],
  });
  render();
}
